export function getWritingStrokeGuide(character: string): WritingStrokeGuide {
  const sinhalaDraft = sinhalaGuides[character];
  if (sinhalaDraft) {
    // These paths are retained only for the educator-review export. Learner-facing
    // code must never receive them until every start, direction and lift is approved.
    return { strokes: [], authored: true, reviewed: false };
  }

  const latinGuide = latinGuides[character.toUpperCase()];
  return latinGuide
    ? { strokes: latinGuide, authored: true, reviewed: true }
    : { strokes: [], authored: false, reviewed: false };
}
